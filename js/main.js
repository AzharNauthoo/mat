// Mobile menu for the site header (.site-nav).
(() => {
    const nav = document.querySelector('.site-nav');
    if (!nav) return;
    const toggle = nav.querySelector('.site-nav__toggle');
    const menu = nav.querySelector('.site-nav__menu');
    const desktop = window.matchMedia('(min-width: 1024px)');

    const setOpen = (open) => {
        nav.classList.toggle('is-open', open);
        toggle.setAttribute('aria-expanded', String(open));
        toggle.setAttribute('aria-label', open ? 'Close menu' : 'Open menu');
    };

    toggle.addEventListener('click', () => setOpen(!nav.classList.contains('is-open')));

    // Close after choosing a link (also needed for same-page anchors such as #sectionForms).
    menu.addEventListener('click', (e) => {
        if (e.target.closest('a')) setOpen(false);
    });

    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && nav.classList.contains('is-open')) {
            setOpen(false);
            toggle.focus();
        }
    });

    document.addEventListener('click', (e) => {
        if (nav.classList.contains('is-open') && !nav.contains(e.target)) setOpen(false);
    });

    desktop.addEventListener('change', (e) => {
        if (e.matches) setOpen(false);
    });
})();

// Sticky nav: adds a soft shadow (.is-scrolled) once the top banner has scrolled away.
// The nav keeps a fixed height so the page never jumps while scrolling.
(() => {
    const nav = document.querySelector('.site-nav');
    if (!nav) return;
    const banner = document.querySelector('.topbar');

    const onScroll = () => {
        const threshold = banner ? banner.offsetHeight : 0;
        nav.classList.toggle('is-scrolled', window.scrollY > threshold);
    };
    window.addEventListener('scroll', onScroll, { passive: true });
    onScroll();
})();

